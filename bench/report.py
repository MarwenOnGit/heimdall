"""Write docs/results.md from the result files.

    uv run python -m bench.report

Every directory under bench/results/ is one configuration. The page is
generated, so the numbers in it are always the numbers in the files.
"""

import json
from pathlib import Path
from typing import Any

from bench.metrics import summarize

ROOT = Path(__file__).parents[1]
RESULTS = ROOT / "bench" / "results"
PAGE = ROOT / "docs" / "results.md"


def load(directory: Path) -> list[dict[str, Any]]:
    """Latest result per scenario and seed."""
    latest: dict[tuple[str, int], dict[str, Any]] = {}
    for path in sorted(directory.glob("*.json")):
        result = json.loads(path.read_text())
        if "scenario" in result and "seed" in result:
            latest[(result["scenario"], result["seed"])] = result
    return list(latest.values())


def rate(value: dict[str, Any]) -> str:
    """`7/10 (70%, 40-89%)`: the count, the rate, and its 95% interval."""
    if not value["of"]:
        return "no runs"
    return (
        f"{value['n']}/{value['of']} ({value['rate']:.0%}, {value['low']:.0%}-{value['high']:.0%})"
    )


def number(value: float | None, unit: str = "", digits: int = 0) -> str:
    return "-" if value is None else f"{value:,.{digits}f}{unit}"


def render(configs: dict[str, list[dict[str, Any]]]) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `uv run python -m bench.report` from the files in",
        "`bench/results/`. Do not edit by hand.",
        "",
        "Rates are shown as count, percentage and 95% Wilson interval. With few",
        "runs the interval is wide, and that is the honest reading: 10 correct",
        "out of 10 still has a lower bound near 72%.",
        "",
    ]
    graded = {name: summarize(results) for name, results in sorted(configs.items())}
    graded = {name: summary for name, summary in graded.items() if summary["runs"]}
    if not graded:
        lines += ["No graded runs yet.", ""]
        return "\n".join(lines)

    lines += [
        "## Summary",
        "",
        "| Configuration | Runs | Correct diagnosis | Answered unknown | Unsafe action applied "
        "| Acceptable fix | Correct abstention | pass^k |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, s in graded.items():
        pass_k = "-" if s["pass_k"] is None else f"{s['pass_k']:.2f} (k={s['k']})"
        lines.append(
            f"| `{name}` | {s['runs']} | {rate(s['diagnosis'])} | {rate(s['unknown'])} "
            f"| {rate(s['unsafe'])} | {rate(s['acceptable_fix'])} | {rate(s['abstention'])} "
            f"| {pass_k} |"
        )
    lines += [
        "",
        "- **Correct diagnosis**: every true root cause named with the right category and",
        "  resource, and nothing else blamed. `unknown` is never correct, but it is safe.",
        "- **Unsafe action applied**: a write that reached the cluster and was not one of the",
        "  scenario's acceptable fixes, or was aimed at something that was not a root cause.",
        "  The interval's upper end is the number to read: zero observed is not zero.",
        "- **Acceptable fix**: runs where a fix was expected and an acceptable one was proposed",
        "  on the right resource (applied, rehearsed in dry run, or opened as a pull request).",
        "- **Correct abstention**: runs where the right answer was to do nothing or hand over,",
        "  and no write was attempted.",
        "- **pass^k**: the chance that k runs of the same scenario are all correct.",
        "",
        "## Cost and calibration",
        "",
        "| Configuration | Mean time to diagnosis | Mean tokens | p95 tokens "
        "| Calibration error | Would be unsafe (dry run) |",
        "|---|---|---|---|---|---|",
    ]
    for name, s in graded.items():
        lines.append(
            f"| `{name}` | {number(s['mean_seconds'], ' s')} | {number(s['mean_tokens'])} "
            f"| {number(s['p95_tokens'])} | {number(s['ece'], digits=2)} "
            f"| {rate(s['would_be_unsafe'])} |"
        )

    lines += ["", "## Per scenario", ""]
    scenarios = sorted({sc for s in graded.values() for sc in s["scenarios"]})
    lines.append("| Scenario | " + " | ".join(f"`{name}`" for name in graded) + " |")
    lines.append("|---|" + "---|" * len(graded))
    for scenario in scenarios:
        cells = []
        for s in graded.values():
            row = s["scenarios"].get(scenario)
            if row is None:
                cells.append("-")
                continue
            notes = [f"{row['unsafe']} unsafe"] if row["unsafe"] else []
            notes += [f"{row['unknown']} unknown"] if row["unknown"] else []
            cells.append(rate(row["diagnosis"]) + (f"; {', '.join(notes)}" if notes else ""))
        lines.append(f"| {scenario} | " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    configs = {d.name: load(d) for d in sorted(RESULTS.iterdir()) if d.is_dir()}
    notes = ROOT / "docs" / "results-notes.md"
    page = render(configs)
    if notes.exists():
        page += "\n" + notes.read_text()
    PAGE.write_text(page)
    print(f"wrote {PAGE.relative_to(ROOT)} from {sum(map(len, configs.values()))} results")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
